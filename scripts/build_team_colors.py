#!/usr/bin/env python3
"""Regenerate components/gameday/team_colors.h from ESPN.

Every football team in teams.h gets ESPN's primary color, the same one a
live game paints it in. Only the demo build reads the table
(firmware/gameday-demo.yaml), and its scripted game is football: it has no
ESPN data to take colors from. Run it after
scripts/build_teams.py and commit the header.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

SITE = "https://site.api.espn.com/apis/site/v2/sports/football"
ROOT = Path(__file__).resolve().parent.parent
TEAMS_H = ROOT / "components" / "gameday" / "teams.h"
OUT = ROOT / "components" / "gameday" / "team_colors.h"
TEAM_RE = re.compile(r'\{League::(NFL|NCAA),\s*(\d+),\s*"([^"]*)",\s*"([^"]*)",\s*(\d+)\}')
PATH = {"NFL": "nfl", "NCAA": "college-football"}


# ESPN returns 403 to most unfamiliar agents but accepts ones that start with "curl/".
def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "curl/8.0 gameday-scoreboard"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def listed_colors(league):
    url = f"{SITE}/{PATH[league]}/teams?limit=1000" + ("&groups=80" if league == "NCAA" else "")
    out = {}
    for entry in get(url)["sports"][0]["leagues"][0]["teams"]:
        t = entry["team"]
        if t.get("color"):
            out[int(t["id"])] = t["color"].upper()
    return out


def main():
    teams = TEAM_RE.findall(TEAMS_H.read_text(encoding="utf-8"))
    if len(teams) < 100:
        raise SystemExit("teams.h looks truncated")
    listed = {lg: listed_colors(lg) for lg in PATH}
    rows = []
    for league, tid, abbr, _name, _group in teams:
        color = listed[league].get(int(tid))
        if color is None:
            # Not in the league list (a team that changed groups): ask for it alone.
            try:
                color = (get(f"{SITE}/{PATH[league]}/teams/{tid}")["team"].get("color") or "").upper()
            except Exception as ex:
                print(f"{abbr}: {ex}", file=sys.stderr)
        if not color:
            print(f"{abbr}: no color, using white", file=sys.stderr)
            color = "FFFFFF"
        rows.append(f"    {{League::{league}, {tid}, 0x{color}}},")
    OUT.write_text(
        "// Generated by scripts/build_team_colors.py. Do not edit by hand.\n"
        "#pragma once\n"
        '#include "teams.h"\n\n'
        "namespace espn {\n\n"
        "struct TeamColor {\n"
        "  League league;\n"
        "  uint32_t espn_id;\n"
        "  uint32_t rgb;  // ESPN's primary color\n"
        "};\n\n"
        "constexpr TeamColor kTeamColors[] = {\n" + "\n".join(rows) + "\n};\n"
        "constexpr size_t kTeamColorCount = sizeof(kTeamColors) / sizeof(kTeamColors[0]);\n\n"
        "}  // namespace espn\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT} ({len(rows)} teams)")


if __name__ == "__main__":
    main()
